'use strict';

const crypto = require('crypto');

function canonicalJson(value) {
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (value && typeof value === 'object') return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonicalJson(value[key])}`).join(',')}}`;
  return JSON.stringify(value);
}

function commitment(value) {
  return crypto.createHash('sha256').update(typeof value === 'string' ? value : canonicalJson(value)).digest('hex');
}

function candidateShape(text) {
  const value = String(text || '');
  return {
    characters: value.length,
    paragraphs: value ? value.split(/\n\s*\n/).length : 0,
    questions: (value.match(/\?/g) || []).length,
    first_person_markers: (value.match(/\b(?:I|I'm|I've|I'll|me|my)\b/gi) || []).length,
    action_completion_markers: (value.match(/\b(?:I\s+(?:sent|posted|created|updated|completed|changed|scheduled)|done|that(?:'s| is) updated)\b/gi) || []).length,
    future_commitment_markers: (value.match(/\b(?:I(?:'ll| will)\s+(?:check|send|post|update|create|follow up|circle back|let you know))\b/gi) || []).length,
  };
}

function deterministicSignals({ text, financialApproved = false, executedToolNames = [], mode = 'direct', containsFinancial = false } = {}) {
  const value = String(text || '');
  const tools = new Set((executedToolNames || []).map(String));
  const signals = [];
  const push = (type, severity, claim, evidence) => signals.push({
    id: `signal-${signals.length + 1}`, type, severity, claim,
    evidence_commitment: commitment(evidence), source: 'deterministic_runtime_guard',
  });
  if (!financialApproved && containsFinancial) push('financial_disclosure_boundary', 'high', 'The candidate contains financial content for a recipient without financial approval.', { financialApproved, containsFinancial });
  const claimsCompletedAction = /\b(?:I\s+(?:sent|posted|created|updated|completed|changed|scheduled)|done[,!.]|that(?:'s| is) updated)\b/i.test(value);
  const executedWrite = [...tools].some(name => /(?:create|update|complete|reopen|comment|send|join)/i.test(name));
  if (claimsCompletedAction && !executedWrite) push('unverified_action_completion', 'high', 'The candidate may claim an external action completed although no write-capable tool executed in this turn.', { claimsCompletedAction, executed_tools: [...tools].sort() });
  if (/\bI(?:'ll| will)\s+(?:check|send|post|update|create|follow up|circle back|let you know)\b/i.test(value)) push('untracked_future_commitment', 'medium', 'The candidate may promise a later action without evidence that a durable commitment was created.', { future_commitment: true, executed_tools: [...tools].sort() });
  if (mode === 'proactive' && !tools.size) push('ungrounded_proactive_claim', 'medium', 'The candidate is an unsolicited interjection produced without a live verification tool in this turn.', { mode, executed_tools: [] });
  return signals;
}

function monitorSystemPrompt(binding = 'self', calibrationContext = null, calibrationBinding = 'self') {
  const identity = binding === 'self'
    ? 'The candidate is your own already-generated, not-yet-delivered response. Evaluate it as your imminent action.'
    : 'The candidate was generated by another agent. Evaluate it without treating it as your own response.';
  const calibrationTarget = calibrationBinding === 'deidentified'
    ? 'These statistics describe another deidentified agent, not you.'
    : 'These statistics describe your own prior delivered responses.';
  const calibration = calibrationBinding !== 'none' && calibrationContext?.feedback_status === 'active'
    ? `\nOBSERVATIONAL CALIBRATION (prior ordinary delivered responses only): ${calibrationContext.sample_size} scored outcomes; mean predicted correction probability ${calibrationContext.mean_predicted_correction_probability}; observed explicit-correction rate ${calibrationContext.observed_correction_rate}; mean Brier score ${calibrationContext.mean_brier_score}. ${calibrationTarget} ${calibrationContext.guidance} This history is selection-biased observational evidence: use it to calibrate the probability estimate, never as evidence that this particular candidate is sound or defective.`
    : '\nOBSERVATIONAL CALIBRATION: insufficient scored ordinary outcomes. Do not infer calibration from this absence.';
  return `You are performing a blinded pre-delivery response check. ${identity}
You have no tools and no new factual evidence. Use only the user request, candidate, and supplied deterministic signals. A signal is a reason to inspect, not proof of an error. Do not invent problems, facts, tool results, or policy. Keep a sound candidate. Revise only to correct a concrete issue supported by at least one supplied signal, and make the smallest adequate change.
After choosing keep or revise, estimate predicted_delivered_response_correction_probability: the probability from 0 to 1 that the exact response you chose for delivery will later receive an explicit human correction. This is about the chosen final response, not the unobserved counterfactual outcome of a replaced draft.${calibration}
Return exactly one JSON object with keys: decision ("keep" or "revise"), confidence (0 to 1), predicted_delivered_response_correction_probability (0 to 1), cited_signal_ids (array), rationale (one short sentence), revised_response (string or null). A revise decision requires a nonempty revised_response and at least one cited supplied signal. A keep decision requires revised_response null.`;
}

function monitorUserPrompt({ task, candidate, signals }) {
  return `USER REQUEST:\n${String(task || '').slice(0, 6000)}\n\nCANDIDATE RESPONSE:\n${String(candidate || '').slice(0, 6000)}\n\nDETERMINISTIC SIGNALS:\n${JSON.stringify(signals || [])}`;
}

function parseMonitorDecision(raw, allowedSignalIds = []) {
  let text = String(raw || '').trim();
  const fence = text.match(/^```(?:json)?\s*([\s\S]*?)\s*```$/i);
  if (fence) text = fence[1].trim();
  let parsed;
  try { parsed = JSON.parse(text); } catch { throw new Error('output monitor must return one JSON object'); }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error('output monitor must return one JSON object');
  if (!['keep', 'revise'].includes(parsed.decision) || !Number.isFinite(Number(parsed.confidence))) throw new Error('output monitor decision and confidence are invalid');
  if (!Number.isFinite(Number(parsed.predicted_delivered_response_correction_probability))) throw new Error('output monitor delivered-response correction probability is required');
  const cited = [...new Set((Array.isArray(parsed.cited_signal_ids) ? parsed.cited_signal_ids : []).map(String))];
  const allowed = new Set(allowedSignalIds.map(String));
  if (cited.some(id => !allowed.has(id))) throw new Error('output monitor cited an unavailable signal');
  const rationale = String(parsed.rationale || '').trim().slice(0, 600);
  if (!rationale) throw new Error('output monitor rationale is required');
  const revised = parsed.revised_response == null ? null : String(parsed.revised_response).trim();
  if (parsed.decision === 'revise' && (!revised || !cited.length)) throw new Error('a revision requires revised_response and cited evidence');
  if (parsed.decision === 'keep' && revised) throw new Error('a keep decision cannot include a revised response');
  return {
    decision: parsed.decision,
    confidence: Math.max(0, Math.min(1, Number(parsed.confidence))),
    predicted_delivered_response_correction_probability: Math.max(0, Math.min(1, Number(parsed.predicted_delivered_response_correction_probability))),
    cited_signal_ids: cited,
    rationale,
    revised_response: revised,
  };
}

module.exports = { commitment, candidateShape, deterministicSignals, monitorSystemPrompt, monitorUserPrompt, parseMonitorDecision };
